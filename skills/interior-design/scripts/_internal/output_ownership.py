"""Verify unchanged, manifest-owned output before any replacement or cleanup.

A filename alone never proves that a file was generated by this skill. Call the
guard before any mutation, then write a new manifest after a successful build.
"""
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re


def _output_path(out):
    original = Path(out).absolute()
    if original.is_symlink():
        raise ValueError('Output cannot be a symlink')
    resolved = original.resolve()
    if resolved.exists() and not resolved.is_dir():
        raise ValueError('Output must be a directory')
    return resolved


def _registered_name(name, manifest_name):
    if not isinstance(name, str):
        raise ValueError('Registered output paths must be text')
    part = PurePosixPath(name)
    if (not name or part.as_posix() != name or part.is_absolute()
            or '..' in part.parts or '\\' in name or ':' in name
            or '\x00' in name or name == manifest_name):
        raise ValueError('Unsafe or reserved registered output path: '+name)
    return part


def _contents(out):
    files, directories = set(), set()
    for directory, children, names in os.walk(out, followlinks=False):
        for name in children + names:
            path = Path(directory)/name
            if path.is_symlink():
                raise ValueError('Output artifacts cannot be symlinks: '+path.relative_to(out).as_posix())
            relative = path.relative_to(out).as_posix()
            if path.is_dir():
                directories.add(relative)
            elif path.is_file():
                files.add(relative)
            else:
                raise ValueError('Unsupported output artifact: '+relative)
    return files, directories


def require_empty_output(out):
    """Accept a new or empty directory without creating or changing it."""
    out = _output_path(out)
    if out.exists() and any(out.iterdir()):
        raise ValueError('Output must be empty; preserve existing files and choose a new directory')
    return out


def verify_inputs_outside(out, paths):
    """Reject inputs inside an output or source directories containing it."""
    out = _output_path(out)
    for value in paths:
        if value is None:
            continue
        path = Path(value).resolve()
        if path == out or path.is_relative_to(out) or (path.is_dir() and out.is_relative_to(path)):
            raise ValueError('Inputs must be outside and separate from output: '+str(value))


def verify_output_directory(out, *, expected=None, manifest_name='manifest.json'):
    """Return a resolved path only after proving every existing artifact's owner.

    Empty/new directories need no manifest. Nonempty output must match the
    producer fields in ``expected`` and contain exactly its registered files and
    their parent directories, with unchanged SHA-256 and optional byte counts.
    """
    out = _output_path(out)
    if not out.exists() or not any(out.iterdir()):
        return out
    if not isinstance(manifest_name, str) or Path(manifest_name).name != manifest_name:
        raise ValueError('Output manifest must be a single filename')
    manifest_path = out/manifest_name
    if manifest_path.is_symlink() or not manifest_path.is_file():
        raise ValueError('Refusing to replace an unmanaged nonempty output directory; choose a new directory')
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    if not isinstance(manifest, dict) or any(manifest.get(key) != value for key, value in (expected or {}).items()):
        raise ValueError('Output manifest does not match the expected producer')
    registered = manifest.get('files')
    if isinstance(registered, dict):
        entries = [dict(name=name, sha256=sha) for name, sha in registered.items()]
    elif isinstance(registered, list):
        entries = registered
    else:
        raise ValueError('Output manifest must register checksummed artifacts')
    names, parent_directories = set(), set()
    for item in entries:
        if not isinstance(item, dict):
            raise ValueError('Invalid output artifact registration')
        part = _registered_name(item.get('name'), manifest_name)
        name = part.as_posix()
        if name in names:
            raise ValueError('Duplicate output artifact: '+name)
        path = out.joinpath(*part.parts)
        if (any(parent.is_symlink() for parent in (path, *path.parents) if parent != out.parent)
                or not path.is_file() or not path.resolve().is_relative_to(out)):
            raise ValueError('Missing or linked output artifact: '+name)
        sha = item.get('sha256')
        if not isinstance(sha, str) or not re.fullmatch(r'[0-9a-f]{64}', sha):
            raise ValueError('Invalid output artifact checksum: '+name)
        if 'bytes' in item and (type(item['bytes']) is not int or item['bytes'] < 0 or path.stat().st_size != item['bytes']):
            raise ValueError('Refusing to replace modified output artifact: '+name)
        with path.open('rb') as stream:
            actual = hashlib.file_digest(stream, 'sha256').hexdigest()
        if actual != sha:
            raise ValueError('Refusing to replace modified output artifact: '+name)
        names.add(name)
        parent_directories.update(parent.as_posix() for parent in part.parents if parent.as_posix() != '.')
    actual_files, actual_directories = _contents(out)
    if actual_files != names | {manifest_name} or actual_directories != parent_directories:
        if any(Path(name).name == '.viewer-session.json' for name in actual_files - names):
            raise ValueError('Stop the review server before replacing this output, or choose a new directory')
        raise ValueError('Output contains unregistered artifacts; preserve them and choose a new directory')
    return out


def write_output_manifest(out, format, manifest_name='manifest.json'):
    """Register controlled orchestration output after a successful build.

    The caller must have verified ownership and input separation before writing
    any children. Runtime server sessions cannot become distributable artifacts.
    """
    out = _output_path(out)
    files, _directories = _contents(out)
    if any(Path(name).name == '.viewer-session.json' for name in files):
        raise ValueError('Stop the review server before registering output')
    entries = []
    for name in sorted(files - {manifest_name}):
        _registered_name(name, manifest_name)
        path = out/name
        with path.open('rb') as stream:
            sha = hashlib.file_digest(stream, 'sha256').hexdigest()
        entries.append(dict(name=name, bytes=path.stat().st_size, sha256=sha))
    result = dict(format=format, files=entries)
    (out/manifest_name).write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    return result
